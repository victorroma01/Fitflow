"""Prueba de los programas de M3: ciclos de Push Pull Leg y Full Body (F-03, F-04), programas según el sexo (F-05),
técnicas de intensidad en los programas y en el entreno (F-02), semana de descarga (F-18 a F-20), rotación de ejercicios
(F-06), «Volver a generar» (F-07) y consejo y ejecución de cada ejercicio (F-13, F-14).

  python3 tests/programs.py dist/stratafit.html
Requiere:  pip install playwright  &&  playwright install chromium   (otro motor: SF_BROWSER=webkit; ver tests/browser.py)
"""
import os, sys, datetime
from playwright.sync_api import sync_playwright
from browser import launch, app_url, context_opts

HERE = os.path.dirname(os.path.abspath(__file__))


def rd(n):
    t = open(os.path.join(HERE, n), encoding='utf-8').read()
    return chr(10).join(l for l in t.split(chr(10)) if not l.startswith('//'))


fails = []


def check(name, cond, info=''):
    if not cond:
        fails.append(name)
    print(('  ok   ' if cond else '  FALLA'), name, ('' if cond else info))


def main(path):
    with sync_playwright() as p:
        b = launch(p)
        c = b.new_context(viewport={'width': 390, 'height': 844}, has_touch=True, is_mobile=True, color_scheme='dark', **context_opts(path))
        c.add_init_script(rd('init.js'))
        pg = c.new_page()
        errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)[:200]))
        # lunes 2 de noviembre de 2026
        pg.clock.install(time=datetime.datetime(2026, 11, 2, 12, 0, 0))
        pg.goto(app_url(path))
        pg.clock.run_for(1200)
        ev = pg.evaluate
        run = lambda ms=400: pg.clock.run_for(ms)
        txt = lambda sel: ev("(e=>e?e.innerText:'')(document.querySelector(%r))" % sel)
        use = lambda i, lv='int': ev("sheet();W=null;S.prog=%d;S.cpi=-1;S.lv='%s';S.plan=levelPlan(parseProgram(%d),'%s',%d);S.wk=1;S.sl=0;S.sel=0;S.done={};S.dl={};S.dls=0;S.rw=1;delete S.rq;S.tab=0;R()" % (i, lv, i, lv, i))

        print('Programas según el sexo (F-05)')
        ev("S.bio={};A.pg()")
        run()
        check('sin sexo indicado, Programas lo pregunta', ev("!!document.querySelector('.pgsx [data-a=pgsx][data-v=F]')"))
        ev("document.querySelector('[data-a=pgsx][data-v=F]').click()")
        run()
        heads = ev("[...document.querySelectorAll('#sh .ph, .sp .ph, .ph')].map(x=>x.innerText.toLowerCase())")
        order = ev("[...document.querySelectorAll('[data-a=pv]')].map(b=>+b.dataset.i)")
        check('mujer: arriba Glúteo y pierna y Full Body, y debajo el resto', order[:2] == [6, 5] and sorted(order[2:]) == [0, 1, 2, 3, 4], str(order))
        check('con sus dos apartados', 'recomendados para ti' in heads and 'otros programas' in heads, str(heads))
        check('se guarda el sexo', ev("S.bio.sex") == 'F')
        ev("S.bio.sex='M';A.pg()")
        run()
        order = ev("[...document.querySelectorAll('[data-a=pv]')].map(b=>+b.dataset.i)")
        check('hombre: arriba Bro Split, Push Pull Leg, Torso / Pierna y Full Body', order[:4] == [0, 3, 2, 5] and sorted(order[4:]) == [1, 4, 6], str(order))
        ev("sheet();S.bio={};S.tab=3;R()")
        run()
        check('en Perfil, el sexo sin indicar se ve como tal', ev("(s=>s&&s.value=='')(document.querySelector('select[data-i=sex]'))"))

        print('Ciclos de Push Pull Leg y Full Body (F-03, F-04)')
        use(3)
        names = ev("S.plan.map(d=>d.n)")
        check('PPL: ciclo de 10 días Push, Pull, descanso, Legs, descanso con los días A y luego los B',
              names == ['Push A', 'Pull A', 'Descanso', 'Legs A', 'Descanso', 'Push B', 'Pull B', 'Descanso', 'Legs B', 'Descanso'], str(names))
        wk = lambda n: ev("[0,1,2,3,4,5,6].map(j=>S.plan[planIndex(j,%d)].n)" % n)
        check('la semana 2 empieza donde acabó la 1', wk(1)[-1] == 'Pull B' and wk(2)[0] == 'Descanso' and wk(2)[1] == 'Legs B', str(wk(1)) + ' / ' + str(wk(2)))
        ev("S.wk=2;R()")
        run()
        btn = ev("[...document.querySelectorAll('.dys .dy')].map(b=>b.innerText.replace(/\\s+/g,' '))")
        check('Workout enseña los 7 días de la semana con sus descansos del ciclo', len(btn) == 7 and [('☾' in x) for x in btn] == [n == 'Descanso' for n in wk(2)], str(btn))
        ev("A.sel(1)")
        run()
        check('al elegir el día 2 de la semana 2, toca Legs B', ev("S.plan[S.sel].n") == 'Legs B' and txt('.hero h2') == 'Legs B', ev("S.plan[S.sel].n"))
        check('la barra de la semana cuenta sus entrenos', '0 de 4 entrenos' in txt('.wk + .dys + div') or '0 de 4 entrenos' in ev("document.body.innerText"), '')
        check('nutrición sigue el ciclo: el lunes de la semana 2 es descanso', ev("S.wk=2;dayInfo('2026-11-02').t") == 'r', ev("JSON.stringify(dayInfo('2026-11-02'))"))
        use(3, 'ini')
        check('PPL principiante: ciclo de 5 días con los días A', ev("S.plan.map(d=>d.n)") == ['Push A', 'Pull A', 'Descanso', 'Legs A', 'Descanso'], str(ev("S.plan.map(d=>d.n)")))
        use(5)
        fb = ev("S.plan.map(d=>d.ex.length>0)")
        check('Full Body: ciclo de 6 días, entreno y descanso alternos con A, B y C', fb == [True, False, True, False, True, False] and ev("S.plan.filter(d=>d.ex.length).map(d=>d.n)") == ['Full Body A', 'Full Body B', 'Full Body C'], str(fb))
        check('Full Body: 3-4 entrenos por semana en la lista de Programas', '3-4 entrenos por semana' in ev("(A.pg(),document.body.innerText)"))
        ev("sheet()")

        print('Técnicas de intensidad (F-02)')
        tech = ev("[0,1,2,3,4,5,6].map(i=>levelPlan(parseProgram(i),'int',i).flatMap(d=>d.ex.map(e=>e.tk)).filter(Boolean).length)")
        check('los programas de fuerza y músculo llevan técnicas; Hyrox e Híbrido, no', all(tech[i] > 0 for i in (0, 2, 3, 5, 6)) and tech[1] == 0 and tech[4] == 0, str(tech))
        allk = ev("[...new Set([0,2,3,5,6].flatMap(i=>['int','ava'].flatMap(l=>levelPlan(parseProgram(i),l,i).flatMap(d=>d.ex.map(e=>e.tk)))).filter(Boolean).flatMap(t=>t.split('+')))].sort()")
        check('entre todos usan las 9 técnicas además de la serie normal', allk == ['CL', 'DS', 'MYO', 'PAR', 'PIR', 'POST', 'PRE', 'RP', 'SS'], str(allk))
        check('en principiante no hay técnicas', ev("[0,2,3,5,6].every(i=>levelPlan(parseProgram(i),'ini',i).every(d=>d.ex.every(e=>!e.tk)))"))
        check('el avanzado cambia algunas (sentadilla en cluster en Bro Split)', ev("levelPlan(parseProgram(0),'ava',0)[4].ex.find(e=>e.n=='Sentadilla').tk") == 'CL')
        check('el ejemplo de la nota: pirámide 12/10/8/6 que acaba en drop set (Torso B)', ev("(e=>e.tk)(levelPlan(parseProgram(2),'int',2)[3].ex[0])") == 'PIR+DS')
        use(0)
        ev("A.go()")
        run(600)
        rows = ev("W.x.map(a=>a.map(s=>(s.k||'WRK')+(s.t?'/'+s.t:'')+':'+s.r))")
        check('pirámide: series PIR de 12, 10, 8 y 6 repeticiones', rows[0] == ['PIR:12', 'PIR:10', 'PIR:8', 'PIR:6'], str(rows[0]))
        ds = ev("S.plan[S.sel].ex.findIndex(e=>e.tk=='DS')")
        check('drop set: la última serie es DS y le sigue la fila de la bajada', rows[ds][-2].startswith('DS:') and rows[ds][-1].startswith('DS/1:'), str(rows[ds]))
        check('la etiqueta de la técnica sustituye a WRK en la serie', ev("[...document.querySelectorAll('#ex0 .wk2')].map(x=>x.innerText)") == ['PIR'] * 4)
        check('antes del drop set no hay descanso', ev("document.querySelectorAll('#ex%d .r2')[%d].children[4].innerText" % (ds, len(rows[ds]) - 2)) == '–')
        check('el objetivo dice la técnica', '12/10/8/6 reps' in txt('#ex0'))
        ev("W=null;R()")
        use(0, 'ava')
        ev("A.go()")
        run(600)
        rp = ev("S.plan[S.sel].ex.findIndex(e=>e.tk=='RP')")
        check('rest-pause (avanzado): bloque extra con 20 s de descanso antes', rp >= 0 and ev("W.x[%d].slice(-1)[0].t" % rp) == 2 and ev("document.querySelectorAll('#ex%d .r2')[%d].children[4].innerText" % (rp, ev("W.x[%d].length" % rp) - 2)) == '0:20', str(rp))
        ev("W=null;S.sl=4;S.sel=4;R();A.go()")
        run(600)
        my = ev("S.plan[S.sel].ex.findIndex(e=>e.tk=='MYO')")
        check('myo-reps (avanzado): serie de activación y mini series de 4 con 15 s', my >= 0 and ev("W.x[%d].slice(1).every(s=>s.r==4&&s.k=='MYO')" % my) and ev("document.querySelectorAll('#ex%d .r2')[0].children[4].innerText" % my) == '0:15', str(my))
        ev("W=null;R()")

        print('Semana de descarga (F-18 a F-20)')
        use(0)
        ev("S.hist={'Press banca':[{d:'2026-10-26',s:[[8,90,0,0],[8,90,0,0],[8,90,0,0],[8,90,0,0]]}]};S.wk=5;S.dls=0;R()")
        run(1200)
        check('semana 5 (intermedio): la semana se marca en naranja', ev("!!document.querySelector('.wk b.wkdl')") and 'descarga' in txt('.wk b'))
        check('tarjeta compacta con «Omitir»', ev("!!document.querySelector('.dl2.dlc2 [data-a=dlx]')"))
        check('al abrir la semana sale una vez la hoja con lo que cambia', ev("!!document.querySelector('#sh .dlw2')") and 'Peso al 65 %' in txt('#sh .dlw2') and ev("S.dls") == 5)
        ev("A.dlok();R()")
        run(1200)
        check('y no vuelve a salir', not ev("!!document.querySelector('#sh .dlw2')"))
        ev("A.go()")
        run(600)
        check('en el entreno: franja naranja con lo que cambia', 'peso al 65 %' in txt('.dlstrip'))
        check('mismas series, 2 repeticiones menos y el 65 % del peso', ev("W.dl") == 1 and ev("W.x[0].length") == 4 and ev("W.x[0].every(s=>s.r==7&&s.w==57.5)"), str(ev("W.x[0].map(s=>s.r+'x'+s.w)")))
        check('sin técnicas de intensidad en la descarga', ev("W.x.every(a=>a.every(s=>!s.k&&!s.t))"))
        check('la sugerencia compara con lo normal', 'normal: 90' in txt('.sgb.dlsg'), txt('.sgb.dlsg'))
        ev("W=null;R()")
        ev("A.dlx()")
        run()
        check('omitir pide confirmación y dice cuándo llega la siguiente', 'semana 10' in txt('#dg'))
        ev("A.dlxx()")
        run()
        check('omitida: esta semana es normal y la siguiente, la 10', not ev("isDeloadWeek(5)") and ev("isDeloadWeek(10)") and 'semana 10' in txt('#tt'))
        ev("A.cpn();A.cpg()")
        run()
        check('programa guiado: se elige la semana de descarga', ev("[...document.querySelectorAll('[data-a=dlch]')].map(b=>b.innerText)") == ['Cada 4 semanas', 'Cada 5', 'Cada 6', 'Otra', 'Nunca'])
        ev("document.querySelector('[data-a=dlch][data-v=o]').click()")
        run()
        check('«Otra» propone cada 8 semanas y se puede cambiar', ev("progDraft.dl") == 8 and ev("document.querySelector('[data-c=dlnw]').value") == '8')
        ev("document.querySelector('[data-a=dlch][data-v=\"4\"]').click()")
        run()
        ev("A.cpgen();A.cps();A.cpa()")
        run()
        check('el programa creado guarda su descarga y la sigue', ev("S.cp[S.cpi].dl") == 4 and ev("isDeloadWeek(4)&&!isDeloadWeek(5)"))
        ev("S.cp[S.cpi].dl=0")
        check('«Nunca»: sin semanas de descarga', not ev("[4,5,6,8,10,12].some(isDeloadWeek)"))
        ev("sheet()")

        print('Rotación de ejercicios (F-06)')
        use(0)
        ev("S.wk=6;R()")
        run()
        check('a las 5 semanas (intermedio) Workout propone rotar', ev("!!document.querySelector('.rtc [data-a=rtv]')"))
        ev("A.rtno()")
        run()
        check('«Ahora no» la aplaza a la semana siguiente', not ev("!!document.querySelector('.rtc')") and ev("(S.wk=7,R(),!!document.querySelector('.rtc'))"))
        ev("A.rtv()")
        run()
        n = ev("document.querySelectorAll('#sh .rtd .mu').length")
        check('antes de rotar se ve qué cambia', n > 5, str(n))
        before = ev("S.plan.map(d=>d.ex.map(e=>e.n))")
        ev("A.rtok()")
        run()
        after = ev("S.plan.map(d=>d.ex.map(e=>e.n))")
        main_lifts = ['Press banca', 'Dominadas', 'Remo con barra', 'Press militar barra', 'Sentadilla', 'Peso muerto rumano']
        check('los accesorios cambian por otra variante', sum(a != b for d1, d2 in zip(before, after) for a, b in zip(d1, d2)) == n)
        check('los básicos se quedan', all(any(m in d for d in after) for m in main_lifts))
        check('y se cuenta desde esta semana', ev("S.rw") == 7 and not ev("!!document.querySelector('.rtc')"))
        check('también se puede rotar a mano desde el menú', ev("(A.menu(),[...document.querySelectorAll('#mn [data-v]')].some(b=>b.dataset.v=='rtv'))"))
        ev("A.mnc()")
        run()

        print('Volver a generar (F-07)')
        ev("A.cpn();A.cpg();A.cpgen()")
        run()
        check('«Volver a generar» con su icono', txt('[data-a=cpvr]') == 'Volver a generar' and ev("!!document.querySelector('[data-a=cpvr] svg')"))
        p0 = ev("JSON.stringify(progDraft.plan.map(d=>d.ex.map(e=>e.n)))")
        ev("A.cpvr()")
        run()
        check('genera otra propuesta', ev("JSON.stringify(progDraft.plan.map(d=>d.ex.map(e=>e.n)))") != p0)
        ev("sheet()")

        print('Consejo y ejecución de cada ejercicio (F-13, F-14)')
        use(0)
        ev("A.go()")
        run(600)
        ev("document.querySelector('#ex0 [data-a=tg][data-v=t]').click()")
        run(300)
        ev("document.querySelector('#ex1 [data-a=tg][data-v=t]').click()")
        run(300)
        tips = ev("[...document.querySelectorAll('.tip')].map(x=>x.innerText)")
        check('Tips enseña el consejo propio de cada ejercicio', len(tips) == 2 and tips[0] != tips[1] and all(len(t) > 30 for t in tips), str(tips))
        ev("document.querySelector('#ex0 .th[data-a=exh]').click()")
        run(300)
        how = txt('#sh .hwp')
        check('al tocar la imagen sale cómo se hace, que no está en el tip', len(how) > 90 and how not in tips[0] and tips[0] not in how, how[:60])
        ev("sheet();W=null;R()")

        errs = [e for e in errs if 'favicon' not in e]
        check('sin errores de JS', not errs, str(errs[:3]))
        b.close()
    print('\n%s' % ('TODO CORRECTO' if not fails else 'FALLAN: ' + ', '.join(fails)))
    sys.exit(1 if fails else 0)


main(sys.argv[1])
