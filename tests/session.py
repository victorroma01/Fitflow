        ev("__sv=[];A.znx()")
        run(100)
        check('tras la serie 1 del segundo, el descanso de la ronda (el del último ejercicio: 1:30)', rest() == 90, str(rest()))
        check('y vuelve al primero, serie 2', cur() == [0, 1], str(cur()))
