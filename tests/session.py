        run(100)
        check('sin descanso automático, pasa enseguida al segundo ejercicio', not rest() and moved() == 'ex1' and cur() == [1, 0], str(ev("__sv")))
        ev("W=null;S.ar=1;delete S.plan[S.sel].ex[1].r;R()")
        go()
        check('sin descanso propio, el de la ronda es de 2:30', 'Descanso de la ronda 2:30' in txt('#ex1 .xh') and ev("document.querySelector('#ex1 .r2').children[4].innerText") == '2:30', txt('#ex1 .xh'))
        ev("W=null;S.plan[S.sel].ex[2].b=S.plan[S.sel].ex[0].b;S.plan[S.sel].ex[1].r=90;R()")
