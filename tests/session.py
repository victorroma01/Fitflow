import os, sys, datetime
from playwright.sync_api import sync_playwright
from browser import launch, app_url, context_opts

HERE = os.path.dirname(os.path.abspath(__file__))


def rd(n):
    t = open(os.path.join(HERE, n), encoding='utf-8').read()
    return chr(10).join(l for l in t.split(chr(10)) if not l.startswith('//'))


fails = []


def check(name, cond, info=''):
    if not cond:
        fails.append(name)
    print(('  ok   ' if cond else '  FALLA'), name, ('' if cond else info))


# anota a qué ejercicio se lleva la pantalla (el desplazamiento es suave y su duración depende del motor)
SPY = """(() => { window.__sv = []; const o = Element.prototype.scrollIntoView;
  Element.prototype.scrollIntoView = function (a) { const x = this.closest('.xs'); __sv.push(x ? x.id : ''); return o.call(this, a); }; })()"""
# luminosidad de un color CSS cualquiera (rgb(), color(srgb …), color-mix…), pasándolo por un lienzo
LUM = """(c => { const x = document.createElement('canvas').getContext('2d'); x.fillStyle = '#000'; x.fillStyle = c; x.fillRect(0, 0, 1, 1);
  const d = x.getImageData(0, 0, 1, 1).data; return .2126 * d[0] + .7152 * d[1] + .0722 * d[2]; })"""


