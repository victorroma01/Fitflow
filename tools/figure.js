const r1 = n => { const s = (Math.round(n * 10) / 10).toFixed(1); return s.endsWith('.0') ? s.slice(0, -2) : s; };
/** Curva cerrada y suave por los puntos (Catmull-Rom → Bézier). Un punto [x, y, 1] es una esquina. */
const smooth = pts => {
  const n = pts.length, P = i => pts[(i + n) % n];
  let d = 'M' + r1(P(0)[0]) + ' ' + r1(P(0)[1]);
  for (let i = 0; i < n; i++) {
    const p0 = P(i - 1), p1 = P(i), p2 = P(i + 1), p3 = P(i + 2);
    const c1 = p1[2] ? p1 : [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = p2[2] ? p2 : [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += 'C' + [c1[0], c1[1], c2[0], c2[1], p2[0], p2[1]].map(r1).join(' ');
  }
  return d + 'Z';
};
const shape = v => Array.isArray(v[0][0]) ? v.map(smooth).join('') : smooth(v);

